export const collectionTime = (date: string | number): string => `${kstTime(date)} KST`;

const transportProblem = (status: number | undefined): string =>
	status === undefined
		? "WCL 연결 오류"
		: status === 429
			? "WCL 요청 한도 초과 (HTTP 429)"
			: `WCL 서버 응답 오류 (HTTP ${status})`;

/** Migrate retained runtime text without displaying arbitrary old errors or ISO times. */
export function retainedCooldownReason(
	reason: string,
	until?: number,
	fallback: string = collectionMessages.previousCooldown,
): string {
	if (
		Object.values(collectionMessages).some((value) => typeof value === "string" && value === reason)
	)
		return reason;
	const budget =
		reason.match(/WCL 포인트 예산 보류 \(([\d.-]+) 남음;/) ??
		reason.match(/WCL 조회 한도 부족 \(남은 포인트 ([\d.-]+)/);
	if (budget && Number.isFinite(Number(budget[1])))
		return collectionMessages.pointBudgetDeferred(Number(budget[1]));
	if (until) {
		const http = reason.match(/WCL (?:.*\()?HTTP (\d+)/);
		if (http) return collectionMessages.transportDeferred(Number(http[1]), until);
		if (/WCL (?:HTTP network|네트워크 오류|연결 오류)/.test(reason))
			return collectionMessages.transportDeferred(undefined, until);
		if (/WCL (?:remaining requests deferred|남은 조회 보류)/.test(reason))
			return collectionMessages.queuedDeferred(until);
	}
	return fallback;
}

/** The reason must be generated by this catalog, never an external error message. */
export function deferredCollectionWarning(reason: string, until?: number): string {
	const retry =
		until && !reason.includes("재시도 가능 시각")
			? ` · 재시도 가능 시각 ${collectionTime(until)}`
			: "";
	return `갱신 보류: ${reason}${retry}. 완료된 성적과 이전 데이터는 유지했습니다.`;
}

/** Show warnings saved by older collectors in the current wording, so old snapshots need no extra font files.
 * Unrecognized text is shown unchanged.
 */
export function displayWarning(warning: string): string {
	if (warning === "실제 Raider.IO 공개 데이터입니다. WCL은 미조회 상태입니다.")
		return collectionMessages.publicOnly;
	const partial = warning.match(/^일부 항목 수집 실패: 캐릭터 (\d+)\/(\d+), 메타 (\d+)\/(\d+)\./);
	if (partial) {
		const [, characters, tracked, meta, trackedMeta] = partial.map(Number);
		return collectionMessages.partialWarning(
			characters as number,
			tracked as number,
			meta as number,
			trackedMeta as number,
		);
	}
	const deferred = warning.match(
		/^갱신 보류: (.+?)(?: · 재시도 가능 시각 (\d{4}-\d{2}-\d{2}T[\d:.]+Z))?\. 완료된 성적과 캐시는 보존했습니다\.$/,
	);
	if (!deferred?.[1]) return warning;
	const until = deferred[2] ? Date.parse(deferred[2]) : undefined;
	const reason =
		deferred[1] === "WCL 미조회 · 캐시 보존"
			? collectionMessages.wclRetained
			: retainedCooldownReason(deferred[1], until, collectionMessages.wclDeferred);
	return deferredCollectionWarning(reason, until);
}
